package dev.toluwalase.jobapp.service;

import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.time.LocalDateTime;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import dev.toluwalase.jobapp.domain.AppUser;
import dev.toluwalase.jobapp.domain.ApplicationKit;
import dev.toluwalase.jobapp.domain.JobCategory;
import dev.toluwalase.jobapp.domain.JobPosting;

/**
 * Unit test suite for PdfExportService.
 * Validates PDF generation, magic byte format (%PDF-), header/bullet/italic formatting,
 * and defensive handling of null/empty inputs.
 */
public class PdfExportServiceTest {

    private PdfExportService pdfExportService;
    private ApplicationKit testKit;

    @BeforeEach
    void setUp() {
        pdfExportService = new PdfExportService();

        AppUser user = new AppUser("tolu", "tolu@example.com", "hash", "LOCAL", "ROLE_USER");
        JobPosting job = new JobPosting(
                "jobtech-101",
                JobCategory.TECHNOLOGY,
                "Senior Java Engineer",
                "Acme Corp",
                "Helsinki",
                "Role description",
                "Java, Spring Boot",
                "https://example.com/job/101",
                "JobTech Nordics",
                LocalDateTime.now()
        );

        String sampleCv = """
                # Toluwalase Ayoola
                **Senior Backend Engineer** | tolu@example.com | +358 40 123 4567 | Helsinki
                > Target Position: Senior Java Engineer at Acme Corp

                ## PROFESSIONAL SUMMARY
                Results-driven software engineer with extensive experience in cloud architecture.

                ## CORE COMPETENCIES & MATCHED EXPERTISE
                - Java & Spring Boot
                - Docker & Kubernetes
                - Microservices Architecture

                ## PROFESSIONAL EXPERIENCE
                ### Lead Software Engineer — Tech Nordic Oy
                *2022 – Present*
                Architected high-throughput services with 99.99% uptime.

                ## EDUCATION & CREDENTIALS
                ### M.Sc. Computer Science — Aalto University
                *2018 – 2020*
                Graduated with honors.
                """;

        String sampleLetter = """
                November 12, 2026

                Hiring Team
                Acme Corp
                Helsinki

                Dear Hiring Team at Acme Corp,

                I am writing to express my enthusiastic interest in the Senior Java Engineer position.
                Having established a solid foundation in Technology & IT, I am confident in my fit.

                Your posting highlights several key qualifications, including Java, Spring Boot. In my work,
                I have consistently demonstrated competence in these domains.

                I welcome the opportunity to discuss how my capabilities can support your upcoming goals.

                Sincerely,

                Toluwalase Ayoola
                tolu@example.com | +358 40 123 4567
                """;

        testKit = new ApplicationKit(
                user,
                job,
                95,
                "High skill alignment",
                sampleCv,
                sampleLetter,
                "DRAFT"
        );
        testKit.setId(101L);
    }

    @Test
    @DisplayName("generateCvPdf produces valid PDF byte stream starting with standard PDF magic bytes")
    void testGenerateCvPdfValid() {
        byte[] pdfBytes = pdfExportService.generateCvPdf(testKit);

        assertNotNull(pdfBytes, "Generated PDF byte array should not be null");
        assertTrue(pdfBytes.length > 500, "PDF should contain rendered binary content");

        // Validate PDF magic bytes: %PDF- (ASCII: 0x25, 0x50, 0x44, 0x46, 0x2D)
        String header = new String(pdfBytes, 0, Math.min(pdfBytes.length, 5));
        assertTrue(header.startsWith("%PDF-"), "Generated byte stream should begin with %PDF- header");
    }

    @Test
    @DisplayName("generateCoverLetterPdf produces valid PDF byte stream starting with standard PDF magic bytes")
    void testGenerateCoverLetterPdfValid() {
        byte[] pdfBytes = pdfExportService.generateCoverLetterPdf(testKit);

        assertNotNull(pdfBytes, "Generated PDF byte array should not be null");
        assertTrue(pdfBytes.length > 500, "PDF should contain rendered binary content");

        String header = new String(pdfBytes, 0, Math.min(pdfBytes.length, 5));
        assertTrue(header.startsWith("%PDF-"), "Generated byte stream should begin with %PDF- header");
    }

    @Test
    @DisplayName("generateCvPdf gracefully handles null or empty kit content without throwing exceptions")
    void testGenerateCvPdfWithEmptyContent() {
        ApplicationKit emptyKit = new ApplicationKit();
        emptyKit.setTailoredCvContent("");

        byte[] pdfBytes = pdfExportService.generateCvPdf(emptyKit);

        assertNotNull(pdfBytes);
        assertTrue(pdfBytes.length > 0);
        String header = new String(pdfBytes, 0, Math.min(pdfBytes.length, 5));
        assertTrue(header.startsWith("%PDF-"));
    }

    @Test
    @DisplayName("generateCoverLetterPdf gracefully handles null or empty kit content without throwing exceptions")
    void testGenerateCoverLetterPdfWithEmptyContent() {
        ApplicationKit emptyKit = new ApplicationKit();
        emptyKit.setTailoredCoverLetterContent("");

        byte[] pdfBytes = pdfExportService.generateCoverLetterPdf(emptyKit);

        assertNotNull(pdfBytes);
        assertTrue(pdfBytes.length > 0);
        String header = new String(pdfBytes, 0, Math.min(pdfBytes.length, 5));
        assertTrue(header.startsWith("%PDF-"));
    }
}

